/** Ejemplo resuelto: pide la ubicacion y muestra latitud y longitud. */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PantallaMapa(vm: MapaViewModel) {
    val estado by vm.estado.collectAsState()

    Scaffold(
        topBar = {
            TopAppBar(
                title = { Text("CampusGPS") },
                colors = TopAppBarDefaults.topAppBarColors(
                    containerColor = MaterialTheme.colorScheme.primary,
                    titleContentColor = MaterialTheme.colorScheme.onPrimary
                )
            )
        }
    ) { padding ->
        Column(
            modifier = Modifier.fillMaxSize().padding(padding).padding(16.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = Arrangement.spacedBy(12.dp)
        ) {
            // TODO Paso 2: pedir el permiso antes de buscar
            Button(onClick = { vm.buscar() }) { Text("Obtener mi ubicación") }

            when (val e = estado) {
                UbicacionUi.Inicial -> Text("Pulsa el botón para ver dónde estás")
                UbicacionUi.Buscando -> Text("Buscando...")
                is UbicacionUi.Lista -> {
                    Text("Latitud: ${e.posicion.latitud}")
                    Text("Longitud: ${e.posicion.longitud}")
                }
                is UbicacionUi.Error -> Text(e.mensaje, color = MaterialTheme.colorScheme.error)
            }
            // TODO Paso 3: MapaUbicacion con Modifier.weight(1f)
        }
    }
}
